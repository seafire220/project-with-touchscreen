// Drives the console in headless Chromium against tests/virtual_device.py. Usage: node console_test.cjs URL CHAR_FILE SHOT_DIR
const { chromium } = require("playwright");
const [url, charFile, shots] = process.argv.slice(2);
const checks = [];
const check = (name, ok) => { checks.push([name, ok]); console.log((ok ? "PASS " : "FAIL ") + name); };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
  await page.goto(url);
  await page.waitForSelector("#login:not([hidden])");
  check("first visit asks to set a password", (await page.textContent("#login-title")) === "Set a password");
  await page.fill("#login-password", "a good password");
  await page.click("#login-form button");
  await page.waitForSelector("#home:not([hidden])");
  check("after setup the home screen shows", true);
  await page.click("#tabs button[data-tab=characters]");
  await page.setInputFiles("#char-file", charFile);
  await page.waitForSelector("#char-list li");
  check("an uploaded character appears", (await page.textContent("#char-list")).includes("Aria"));
  await page.click("#tabs button[data-tab=home]");
  check("it becomes the active character", (await page.textContent("#home-name")) === "Aria");
  await page.fill("#say-text", "hello there");
  await page.click("#say-form button");
  await page.waitForFunction(() => document.querySelector("#log").textContent.includes("stand-in reply"), null, { timeout: 10000 });
  check("typed words get a spoken reply in the log", true);
  check("the timer tag is acted on, not read out", (await page.textContent("#log")).includes("Timer:") && !(await page.textContent("#log")).includes("[timer"));
  await page.screenshot({ path: shots + "/console-home.png", fullPage: true });
  await page.click("#tabs button[data-tab=services]");
  await page.waitForSelector("#keys .key");
  const row = page.locator("#keys .key").first();
  await row.locator("input").fill("sk-very-secret-test-key-123");
  await row.locator("button").first().click();
  await page.waitForFunction(() => document.querySelector("#keys").textContent.includes("(set)"));
  check("a saved key shows as set", true);
  const html = await page.content();
  check("the key itself never comes back to the page", !html.includes("sk-very-secret"));
  await page.screenshot({ path: shots + "/console-services.png", fullPage: true });
  await page.click("#tabs button[data-tab=memory]");
  await page.waitForFunction(() => document.querySelector("#mem-history").textContent.includes("hello there"));
  check("the conversation shows in memory", true);
  await page.click("#tabs button[data-tab=device]");
  await page.click("#btn-logout");
  await page.waitForSelector("#login:not([hidden])");
  check("logging out returns to the login", (await page.textContent("#login-title")) === "Log in");
  check("no script errors", errors.length === 0 || (console.log(errors), false));
  await browser.close();
  process.exit(checks.every(([, ok]) => ok) ? 0 : 1);
})().catch((e) => { console.error(e); process.exit(2); });
